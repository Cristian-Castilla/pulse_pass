-- V4__security_credentials_roles.sql
-- PulsePass — Fase 4: Capa de Seguridad
--
-- Este archivo se construye en dos pasos:
--   Etapa 0: ALTER TABLE events (event_date DATE -> TIMESTAMP) para alinear
--            el esquema con el tipo LocalDateTime del PRD de Servicios.
--   Etapa 2: tablas user_credentials y user_roles.
--
-- Nunca se modifica una migración ya aplicada: V1 declara event_date DATE,
-- por eso el cambio de tipo se hace aquí y no en V1.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Etapa 0 — Alineación de tipo: event_date pasa de DATE a TIMESTAMP
-- Motivo: el PRD de Servicios §12 declara CreateEventRequest.eventDate como
-- LocalDateTime, y el código se alineó a ese tipo. Hibernate opera con
-- ddl-auto=validate, por lo que el esquema debe coincidir con la entidad.
-- -----------------------------------------------------------------------------
ALTER TABLE events
    ALTER COLUMN event_date TYPE TIMESTAMP;

-- -----------------------------------------------------------------------------
-- B) Etapa 2 — Credenciales y roles
-- -----------------------------------------------------------------------------

-- Tabla: user_credentials (1:1 con users)
--
-- PRD de Seguridad §9.1: "UserCredential (NUEVA, 1:1 con User)
--   ├── user_id (PK y FK unique)
--   ├── password_hash (NOT NULL)
--   └── password_changed_at (opcional)"
--
-- user_id es PK y FK a la vez: la entidad usa @MapsId, de modo que el id de la
-- credencial ES el id del usuario. Eso garantiza el 1:1 sin columna extra.
--
-- password_hash es VARCHAR(100): un hash BCrypt tiene 60 caracteres, y el
-- margen cubre otros formatos de hash si en el futuro se cambia el encoder.
--
-- NO se insertan filas en esta migración. PRD §9.2: "Crear procedimiento seguro
-- para vincular credenciales de usuarios preexistentes sin asignar contraseñas
-- conocidas o compartidas. Los registros legados sin credenciales quedarán sin
-- posibilidad de login hasta una activación segura; no se debe inventar un
-- password predeterminado." Eso se resuelve en la Etapa 3 (PasswordEncoder) y
-- en la semilla de tests (opción 5 de D2).
-- -----------------------------------------------------------------------------
CREATE TABLE user_credentials (
    user_id             BIGINT       NOT NULL,
    password_hash       VARCHAR(100) NOT NULL,
    password_changed_at TIMESTAMP,

    CONSTRAINT pk_user_credentials
        PRIMARY KEY (user_id),

    CONSTRAINT fk_user_credentials_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

-- -----------------------------------------------------------------------------
-- Tabla: user_roles (N:1 con users)
--
-- PRD de Seguridad §9.1: "UserRole (NUEVA, N:1 con User)
--   ├── user_id (FK)
--   └── role (USER | STAFF | ADMIN) PK(user_id, role)"
--
-- La PK compuesta del PRD se expresa como UNIQUE(user_id, role): la identidad
-- de la fila la da la combinación usuario+rol. Un rol repetido para el mismo
-- usuario no aporta nada, y sin esta constraint un INSERT duplicado pasaría.
--
-- El CHECK restringe el rol al catálogo del enum Role, de la misma forma que
-- events.category y events.status ya se restringen en V1.
-- -----------------------------------------------------------------------------
CREATE TABLE user_roles (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT      NOT NULL,
    role    VARCHAR(20) NOT NULL,

    CONSTRAINT uk_user_role
        UNIQUE (user_id, role),

    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (user_id) REFERENCES users (id),

    CONSTRAINT chk_user_role
        CHECK (role IN ('USER', 'STAFF', 'ADMIN'))
);

-- -----------------------------------------------------------------------------
-- Índices
--
-- El login se resuelve por username o por email (PRD §10 FR-SEC-AUTH-002:
-- "Autentica usuario/correo + contraseña"). Ambas búsquedas navegan
-- user_credentials -> users, y users.username / users.email ya tienen UNIQUE
-- en V1, así que están cubiertas. El índice que sí aporta valor aquí es el de
-- user_roles.user_id, que es una FK sin índice propio.
-- -----------------------------------------------------------------------------
CREATE INDEX idx_user_roles_user_id
    ON user_roles (user_id);
